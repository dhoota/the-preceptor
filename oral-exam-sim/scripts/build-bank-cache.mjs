#!/usr/bin/env node
// Generates src/cases/generated/encoded.ts and src/samps/generated/encoded.ts:
// lightly obfuscated snapshots of the case and SAMP banks (base64 + a
// repeating-key XOR), so a plain `unzip app.apk && cat` (or grep on the
// built JS) doesn't hand someone the whole content bank as readable text.
// The real source of truth stays src/cases/source.ts and src/samps/source.ts
// (and the per-batch files they read), which this script bundles.
//
// This is NOT encryption. Each key lives in this file and in the matching
// src/*/decode.ts, right next to the blob it unlocks, and anyone who finds
// the blob can find the key just as easily. It only raises the bar against
// casual scraping of the shipped bundle, not against someone who
// decompiles the app.
//
// Run automatically by "npm run dev", "npm test" and "npm run build" (see
// package.json). The outputs are gitignored: always regenerated from
// src/cases/** and src/samps/**, never a stale, committed snapshot.
import { build } from "esbuild";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function xor(bytes, key) {
  const keyBytes = Buffer.from(key, "utf8");
  const out = Buffer.alloc(bytes.length);
  for (let i = 0; i < bytes.length; i++) out[i] = bytes[i] ^ keyBytes[i % keyBytes.length];
  return out;
}

async function bundleAndImport(entry, tmpName) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: "esm",
    platform: "node",
    target: "node18",
    logLevel: "silent",
  });
  const tmpFile = path.join(path.dirname(entry), tmpName);
  await writeFile(tmpFile, result.outputFiles[0].text);
  try {
    return await import(`${pathToFileURL(tmpFile).href}?t=${Date.now()}`);
  } finally {
    await rm(tmpFile, { force: true });
  }
}

async function writeEncoded(outDir, outFile, key, payload, label, count) {
  await mkdir(outDir, { recursive: true });
  const encoded = xor(Buffer.from(JSON.stringify(payload), "utf8"), key).toString("base64");
  const header = `// AUTO-GENERATED by scripts/build-bank-cache.mjs. Do not edit by hand —
// your changes are overwritten on the next build. This file is gitignored.
// Obfuscated (base64 + XOR) snapshot, decoded at runtime by the matching
// decode.ts. Not encryption — see build-bank-cache.mjs.
`;
  await writeFile(outFile, `${header}export const BANK_BLOB: string = ${JSON.stringify(encoded)};\n`);
  console.log(`build-bank-cache: wrote ${count} ${label} (${encoded.length} bytes base64) to ${path.relative(root, outFile)}`);
}

async function heldBackIds(dir) {
  const ids = new Set();
  let files;
  try {
    files = await readdir(dir);
  } catch {
    return ids;
  }
  for (const f of files) {
    if (!f.endsWith(".json")) continue;
    const data = JSON.parse(await readFile(path.join(dir, f), "utf8"));
    for (const id of Object.keys(data.ids ?? {})) ids.add(id);
  }
  return ids;
}

async function buildCases() {
  // Mirrors src/cases/decode.ts. Keep the two in sync.
  const KEY = "preceptor-ccfpem-cases-v1";
  const mod = await bundleAndImport(path.join(root, "src/cases/source.ts"), `.bundle-cases-${process.pid}.mjs`);
  const { CASES } = mod;
  if (!Array.isArray(CASES) || !CASES.length) throw new Error("build-bank-cache: CASES came back empty — refusing to write an empty bank.");
  await writeEncoded(path.join(root, "src/cases/generated"), path.join(root, "src/cases/generated/encoded.ts"), KEY, CASES, "cases", CASES.length);
}

async function buildSamps() {
  // Mirrors src/samps/decode.ts. Keep the two in sync.
  const KEY = "preceptor-ccfpem-samps-v1";
  // batches.ts has no import.meta.glob (a Vite-only feature this plain
  // esbuild+Node bundle can't evaluate), unlike source.ts. The held-back
  // filter that source.ts applies via that glob is replicated here instead.
  const mod = await bundleAndImport(path.join(root, "src/samps/batches.ts"), `.bundle-samps-${process.pid}.mjs`);
  const { AUTHORED_SAMPS } = mod;
  if (!Array.isArray(AUTHORED_SAMPS) || !AUTHORED_SAMPS.length) {
    throw new Error("build-bank-cache: AUTHORED_SAMPS came back empty — refusing to write an empty bank.");
  }
  const held = await heldBackIds(path.join(root, "src/samps/held-back"));
  const samps = AUTHORED_SAMPS.filter((s) => !held.has(s.id));
  await writeEncoded(path.join(root, "src/samps/generated"), path.join(root, "src/samps/generated/encoded.ts"), KEY, samps, "samps", samps.length);
  console.log(`build-bank-cache: held back ${held.size} samp(s) from the snapshot`);
}

async function main() {
  await buildCases();
  await buildSamps();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
