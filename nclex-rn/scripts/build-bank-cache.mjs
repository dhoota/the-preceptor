#!/usr/bin/env node
// Generates src/bank/generated/encoded.ts: a lightly obfuscated snapshot of
// the question/case bank (base64 + a repeating-key XOR), so a plain
// `unzip app.apk && cat` (or grep on the built JS) doesn't hand someone the
// whole item bank as readable text. The real source of truth stays the
// per-batch files in src/bank/**, which this script reads and bundles.
//
// This is NOT encryption. The key lives in this file and in
// src/bank/decode.ts, right next to the blob it unlocks, and anyone who
// finds the blob can find the key just as easily. It only raises the bar
// against casual scraping of the shipped bundle, not against someone who
// decompiles the app.
//
// Run automatically by "npm run dev", "npm test" and "npm run build" (see
// package.json). The output is gitignored: it is always regenerated from
// src/bank/** and never a stale, committed snapshot.
import { build } from "esbuild";
import { mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entry = path.join(root, "src/bank/index.ts");
const outDir = path.join(root, "src/bank/generated");
const outFile = path.join(outDir, "encoded.ts");
const tmpFile = path.join(outDir, `.bundle-${process.pid}.mjs`);

// Mirrors src/bank/decode.ts. Keep the two in sync.
const KEY = "preceptor-nclex-bank-v1";

function xor(bytes, key) {
  const keyBytes = Buffer.from(key, "utf8");
  const out = Buffer.alloc(bytes.length);
  for (let i = 0; i < bytes.length; i++) out[i] = bytes[i] ^ keyBytes[i % keyBytes.length];
  return out;
}

async function main() {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: "esm",
    platform: "node",
    target: "node18",
    logLevel: "silent",
  });
  await mkdir(outDir, { recursive: true });
  await writeFile(tmpFile, result.outputFiles[0].text);
  let mod;
  try {
    mod = await import(`${pathToFileURL(tmpFile).href}?t=${Date.now()}`);
  } finally {
    await rm(tmpFile, { force: true });
  }
  const { ITEMS, CASES } = mod;
  if (!Array.isArray(ITEMS) || !Array.isArray(CASES) || !ITEMS.length || !CASES.length) {
    throw new Error("build-bank-cache: ITEMS/CASES came back empty — refusing to write an empty bank.");
  }
  const payload = JSON.stringify({ items: ITEMS, cases: CASES });
  const encoded = xor(Buffer.from(payload, "utf8"), KEY).toString("base64");

  const header = `// AUTO-GENERATED by scripts/build-bank-cache.mjs from src/bank/**. Do not
// edit by hand — your changes are overwritten on the next build. This file
// is gitignored.
// Obfuscated (base64 + XOR) snapshot of the bank, decoded at runtime by
// src/bank/decode.ts. Not encryption — see build-bank-cache.mjs.
`;
  await writeFile(outFile, `${header}export const BANK_BLOB: string = ${JSON.stringify(encoded)};\n`);
  console.log(
    `build-bank-cache: wrote ${ITEMS.length} items, ${CASES.length} cases (${encoded.length} bytes base64) to ${path.relative(root, outFile)}`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
